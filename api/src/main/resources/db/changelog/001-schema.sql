--changeset derops:001-extensions
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE EXTENSION IF NOT EXISTS btree_gist;

--changeset derops:001-title
CREATE TABLE title (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         varchar(200) NOT NULL,
    kind         varchar(20)  NOT NULL CHECK (kind IN ('FILM', 'SERIES', 'DOCUMENTARY')),
    release_year integer      CHECK (release_year BETWEEN 1888 AND 2100),
    external_id  varchar(64)  UNIQUE,
    created_at   timestamp with time zone NOT NULL DEFAULT now()
);
--rollback DROP TABLE title;

--changeset derops:001-license-window
CREATE TABLE license_window (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title_id   bigint      NOT NULL REFERENCES title (id) ON DELETE CASCADE,
    territory  varchar(2)  NOT NULL CHECK (territory ~ '^[A-Z]{2}$'),
    platform   varchar(10) NOT NULL CHECK (platform IN ('SVOD', 'AVOD', 'TVOD', 'LINEAR')),
    start_date date        NOT NULL,
    end_date   date        NOT NULL,
    exclusive  boolean     NOT NULL DEFAULT false,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT ck_window_dates CHECK (start_date <= end_date),
    -- Two exclusive windows for the same title, territory and platform may never overlap,
    -- even when two requests race past the application check at the same moment.
    CONSTRAINT ex_exclusive_overlap EXCLUDE USING gist (
        title_id WITH =,
        territory WITH =,
        platform WITH =,
        daterange(start_date, end_date, '[]') WITH &&
    ) WHERE (exclusive)
);
--rollback DROP TABLE license_window;
